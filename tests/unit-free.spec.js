test.describe('свободная речь: куски в любом порядке', () => {
  test('новых фраз не меньше 40, а вместе с прежними — больше 50', () => {
    expect(groups.reduce((n, g) => n + g.phrases.length, 0)).toBeGreaterThanOrEqual(40);
  });
  for (const g of groups) {
    for (const phrase of g.phrases) {
      test(g.name + ': ' + phrase, () => {
        const r = P(phrase);
        for (const [k, v] of Object.entries(g.expect)) expect(r[k], k).toEqual(v);
      });
    }
  }
  test('убрать один кусок не ломает остальные', () => {
    const full = P('дежурство в семинарии с 16:00 до четверга 16:00, повторяющееся');
    const noArea = P('дежурство с 16:00 до четверга 16:00, повторяющееся');
    const noRepeat = P('дежурство в семинарии с 16:00 до четверга 16:00');
    const noEnd = P('дежурство в семинарии с 16:00, повторяющееся');
    expect(noArea).toMatchObject({ areaId: null, time: '16:00', endTime: '16:00', endDate: '2026-10-01', text: 'Дежурство' });
    expect(noArea.block).toEqual(full.block);
    expect(noRepeat).toMatchObject({ areaId: 'sem', time: '16:00', endDate: '2026-10-01', repeat: null, block: null });
    expect(noEnd).toMatchObject({ areaId: 'sem', time: '16:00', endTime: null, repeat: { kind: 'weekly', days: [1] } });
  });
  test('нераспознанное остаётся частью текста', () => {
    expect(P('обсудить с отцом Сергием ремонт притвора завтра в 12').text).toBe('Обсудить с отцом Сергием ремонт притвора');
    expect(P('с утра подумать о проповеди').text).toBe('Подумать о проповеди');
  });
  test('прошедшее время начала — ближайший будущий день', () => {
    expect(P('дежурство с 9:00 до 12:00').date).toBe('2026-09-29');
  });
  test('окончание раньше начала — на следующий день', () => {
    expect(P('ночное дежурство с 20:00 до 8 утра')).toMatchObject({ date: '2026-09-28', time: '20:00', endDate: '2026-09-29', endTime: '08:00', dur: 720 });
  });
  test('фишки: начало, окончание, блок', () => {
    const keys = P('приём с 10 до 12, каждый вторник').chips.map((c) => c.key);
    expect(keys).toEqual(expect.arrayContaining(['time', 'end', 'block']));
  });
});
